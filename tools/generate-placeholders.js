/* ============================================================================
   PLACEHOLDER IMAGE GENERATOR
   ----------------------------------------------------------------------------
       node tools/generate-placeholders.js

   Reads every `image:` path from data/products.js. For each one that does not
   exist yet it writes a matching preview placeholder next to it:

       assets/products/charizard-base-set.jpg   <-- you drop your photo here
       assets/products/_placeholders/charizard-base-set.svg   <-- preview

   How the site behaves with missing photos: the <img> fails to load and the
   site instantly draws a branded monogram placeholder inline. Nothing breaks,
   no broken-image icons, no layout shift. Replace the .jpg with a real photo
   and it appears automatically.

   Never overwrites an existing file unless you pass --force.
   ========================================================================== */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DATA = path.join(ROOT, "data", "products.js");
const FORCE = process.argv.includes("--force");

const src = fs.readFileSync(DATA, "utf8");

/* Pull `name:` / `image:` pairs straight out of the data file (either order). */
const entries = [];
function collect(name, image) {
  if (!entries.some((e) => e.image === image)) entries.push({ name, image });
}
let m;
const reA = /name:\s*"([^"]+)"[\s\S]{0,400}?image:\s*"([^"]+)"/g;
while ((m = reA.exec(src)) !== null) collect(m[1], m[2]);
const reB = /image:\s*"([^"]+)"[\s\S]{0,400}?name:\s*"([^"]+)"/g;
while ((m = reB.exec(src)) !== null) collect(m[2], m[1]);

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function placeholder(name, hint) {
  const initial = esc((name || "?").trim().charAt(0).toUpperCase());
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 800" width="800" height="800">
  <title>${esc(name)} — placeholder</title>
  <defs>
    <radialGradient id="bg" cx="50%" cy="26%" r="78%">
      <stop offset="0%" stop-color="#1d1a20"/>
      <stop offset="58%" stop-color="#101015"/>
      <stop offset="100%" stop-color="#08080b"/>
    </radialGradient>
    <linearGradient id="gold" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="#f4e6c4"/>
      <stop offset="45%" stop-color="#d8b672"/>
      <stop offset="100%" stop-color="#a8873f"/>
    </linearGradient>
  </defs>
  <rect width="800" height="800" fill="url(#bg)"/>
  <circle cx="400" cy="400" r="232" fill="none" stroke="url(#gold)" stroke-opacity=".36" stroke-width="1.4"/>
  <circle cx="400" cy="400" r="196" fill="none" stroke="#c1121f" stroke-opacity=".3" stroke-width="1"/>
  <text x="400" y="300" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="17" letter-spacing="7" fill="#7d7a85">TEAM ROCKETS EXCHANGE</text>
  <text x="400" y="500" text-anchor="middle" font-family="Georgia,'Times New Roman',serif" font-size="240" fill="url(#gold)" fill-opacity=".92">${initial}</text>
  <text x="400" y="618" text-anchor="middle" font-family="Helvetica,Arial,sans-serif" font-size="26" letter-spacing="4" fill="#e6e3dc">${esc(hint)}</text>
</svg>
`;
}

let created = 0;
let havePhoto = 0;
let havePreview = 0;
const available = [];

for (const entry of entries) {
  const imagePath = path.join(ROOT, entry.image);
  const imageDir = path.dirname(imagePath);
  const base = path.basename(imagePath).replace(/\.[a-z0-9]+$/i, "");
  const previewDir = path.join(imageDir, "_placeholders");
  const previewPath = path.join(previewDir, `${base}.svg`);
  const setHint = base.replace(/[-_]+/g, " ").toUpperCase();

  fs.mkdirSync(imageDir, { recursive: true });

  const photoExists = fs.existsSync(imagePath) && fs.statSync(imagePath).size > 0;
  if (photoExists) {
    havePhoto++;
    available.push(entry.image);
    console.log(`· photo   ${entry.image}`);
  } else {
    console.log(`○ missing ${entry.image}  (site draws a branded placeholder, no request made)`);
  }

  if (fs.existsSync(previewPath) && !FORCE) {
    havePreview++;
    continue;
  }
  fs.mkdirSync(previewDir, { recursive: true });
  fs.writeFileSync(previewPath, placeholder(entry.name, setHint), "utf8");
  created++;
}

/* Manifest: the page only requests photos that really exist, so a card without
   a photo yet costs zero network requests and shows the inline placeholder. */
const manifestPath = path.join(ROOT, "data", "photo-manifest.js");
const manifest =
  "/* GENERATED by tools/generate-placeholders.js - do not edit by hand.\n" +
  "   Lists the product photos that exist on disk. Re-run the generator after\n" +
  "   adding or replacing images. */\n" +
  "window.TRE_PHOTOS = " +
  JSON.stringify({ generated: new Date().toISOString().slice(0, 10), available }, null, 2) +
  ";\n";
fs.writeFileSync(manifestPath, manifest, "utf8");

console.log(
  `\n${entries.length} product image(s) referenced · ${havePhoto} real photo(s) present · ` +
  `${entries.length - havePhoto} awaiting a photo · ${created} preview placeholder(s) written.`
);
console.log(`Manifest: data/photo-manifest.js (${available.length} photo(s) will be requested).`);
console.log("Previews live in assets/products/_placeholders/ — open them to see the intended filenames.\n");
